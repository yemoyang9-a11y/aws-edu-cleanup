#!/usr/bin/env python3
"""Print ONE copy-paste block for AWS CloudShell (standard library only).

The block recreates common/session.py and cfn_predelete/predelete_stacks.py under
~/edu-cleanup with heredocs, runs the dry-run, and asks for "DELETE" before --apply.

    python3 cfn_predelete/make_cloudshell_block.py > cloudshell_block.txt
    python3 cfn_predelete/make_cloudshell_block.py --regions ap-northeast-2 --timeout-min 20
    python3 cfn_predelete/make_cloudshell_block.py --update-readme   # refresh the block in README.md
"""
import argparse
import re
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = ["common/session.py", "cfn_predelete/predelete_stacks.py"]
TARGET = "$HOME/edu-cleanup"
README = Path(__file__).resolve().parent / "README.md"
BEGIN = "<!-- BEGIN CLOUDSHELL BLOCK (generated by make_cloudshell_block.py --update-readme; do not edit by hand) -->"
END = "<!-- END CLOUDSHELL BLOCK -->"


def build_block(regions: str, timeout_min: float, extra: str = "") -> str:
    lines = ["# --- edu-cleanup cfn_predelete: CloudShell block (paste all at once) ---",
             f'mkdir -p "{TARGET}/common" "{TARGET}/cfn_predelete" && touch "{TARGET}/common/__init__.py"']
    for rel in FILES:
        text = (ROOT / rel).read_text(encoding="utf-8")
        tag = "EDU_" + re.sub(r"[^A-Z0-9]", "_", rel.upper())
        if re.search(rf"^{tag}$", text, re.M):
            raise SystemExit(f"heredoc terminator {tag} occurs in {rel}")
        lines += [f"cat > \"{TARGET}/{rel}\" <<'{tag}'", text.rstrip("\n"), tag]
    args = f"--regions {shlex.quote(regions)} --timeout-min {timeout_min:g}" + (f" {extra}" if extra else "")
    script = f'"{TARGET}/cfn_predelete/predelete_stacks.py"'
    # last line on purpose: `read` must not swallow pasted lines
    lines.append(
        f"python3 {script} {args} --json-out ~/cfn-predelete-dryrun.json; "
        f"read -r -p '위 목록을 실제로 삭제하려면 DELETE 를 입력하세요: ' EDU_OK; "
        f"if [ \"$EDU_OK\" = DELETE ]; then python3 {script} {args} --apply --json-out ~/cfn-predelete-apply.json; "
        f"echo \"exit=$?  (0=모두 삭제, 1=TIMEOUT/FAILED 남음 -> 한 번 더 실행, 2=오류)\"; "
        f"else echo '취소: 아무것도 삭제하지 않았습니다'; fi")
    return "\n".join(lines) + "\n"


def readme_section(block: str) -> str:
    return f"{BEGIN}\n```bash\n{block}```\n{END}"


def update_readme(block: str, path: Path = README) -> bool:
    text = path.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + readme_section(block) + text[end:]
    if new != text:
        path.write_text(new, encoding="utf-8")
    return new != text


def readme_block(path: Path = README) -> str:
    text = path.read_text(encoding="utf-8")
    return text[text.index(BEGIN):text.index(END) + len(END)]


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--regions", default="ap-northeast-2,us-east-1")
    p.add_argument("--timeout-min", type=float, default=25.0,
                   help="default 25: CloudShell ends idle sessions after 20-30 min without keyboard input")
    p.add_argument("--extra", default="", help='extra flags, e.g. "--cfn-role-arn arn:aws:iam::...:role/X"')
    p.add_argument("--update-readme", action="store_true", help="write the default block into README.md")
    a = p.parse_args(argv)
    if a.update_readme:
        changed = update_readme(build_block("ap-northeast-2,us-east-1", 25.0))
        print("README.md updated" if changed else "README.md already up to date", file=sys.stderr)
        return 0
    sys.stdout.write(build_block(a.regions, a.timeout_min, a.extra))
    return 0


if __name__ == "__main__":
    sys.exit(main())
